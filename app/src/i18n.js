export const dicts = { en, ar: null };
/** Loads the Arabic dictionary once; resolves immediately when already loaded. */
export function loadLanguage(lang) {
  if (lang !== 'ar' || dicts.ar) return Promise.resolve();
  return import('./i18n-ar.js').then((m) => { dicts.ar = m.ar; });
}
export const LOCALES = { en: 'en-AE', ar: 'ar-AE' };

export const I18nContext = createContext({ lang: 'en', t: (k) => k });
export const useI18n = () => useContext(I18nContext);

export function makeT(lang) {
  const d = dicts[lang] || en;
  return (key, params) => {
    if (params && Number(params.n) === 1 && d[key + '.one']) key += '.one';
    let s = d[key] ?? en[key] ?? key;
    // Isolate interpolated text (titles, names) so Arabic and English runs never reorder each other.
    if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v == null || v === '' ? '' : `\u2068${v}\u2069`);
    return s;
  };
}

export function makeFormat(lang) {
  const locale = LOCALES[lang] || 'en-AE';
  const nf = new Intl.NumberFormat(locale, { maximumFractionDigits: 2 });
  const date = (iso, opts = { weekday: 'short', day: 'numeric', month: 'short' }) =>
    new Intl.DateTimeFormat(locale, { ...opts, timeZone: 'UTC' }).format(new Date(iso.length === 10 ? iso + 'T12:00:00Z' : iso));
  const dateTime = (iso) =>
    new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short', year: 'numeric', hour: 'numeric', minute: '2-digit', timeZone: 'Asia/Dubai' }).format(new Date(iso));
  const time = (hhmm) =>
    new Intl.DateTimeFormat(locale, { hour: 'numeric', minute: '2-digit', timeZone: 'UTC' }).format(new Date(`1970-01-01T${hhmm}:00Z`));
  const num = (n) => nf.format(n);
  const sep = lang === 'ar' ? '، ' : ', ';
  const clock = (iso) => new Intl.DateTimeFormat(locale, { hour: 'numeric', minute: '2-digit', timeZone: 'Asia/Dubai' }).format(new Date(iso));
  return { locale, date, dateTime, time, num, sep, clock };
}
